#!/usr/bin/env node

const fs = require("fs");

const msgPath = process.argv[2];

if (!msgPath) {
  console.error("\x1b[31m[ERROR]\x1b[0m Commit message file path was not provided.");
  process.exit(1);
}

let rawMessage;
try {
  rawMessage = fs.readFileSync(msgPath, "utf8");
} catch (err) {
  console.error(`\x1b[31m[ERROR]\x1b[0m Could not read commit message file: ${err.message}`);
  process.exit(1);
}

// Strip comments and empty lines
const lines = rawMessage
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line.length > 0 && !line.startsWith("#"));

if (lines.length === 0) {
  console.error("\x1b[31m[ERROR]\x1b[0m Commit message cannot be empty.");
  process.exit(1);
}

const firstLine = lines[0];

// Ignore automatic merge or revert commits generated by git
if (
  firstLine.startsWith("Merge ") ||
  firstLine.startsWith("Revert \"") ||
  firstLine.startsWith("Initial commit")
) {
  process.exit(0);
}

// Standard allowed commit types
const ALLOWED_TYPES = [
  "feat",
  "fix",
  "docs",
  "style",
  "refactor",
  "perf",
  "test",
  "build",
  "ci",
  "chore",
  "revert",
];

const typesPattern = ALLOWED_TYPES.join("|");

// Enforces exact format: "<type>: <message>" (no brackets, exactly one space after colon)
const commitRegex = new RegExp(
  `^(${typesPattern})(?:\\([a-z0-9._-]+\\))?: [^\\s].*$`,
  "i"
);

if (!commitRegex.test(firstLine)) {
  console.error("\n\x1b[41m\x1b[37m ✖ INVALID COMMIT MESSAGE FORMAT \x1b[0m\n");
  console.error(`Your commit message was:\n  \x1b[31m"${firstLine}"\x1b[0m\n`);
  console.error("Commit messages must follow this format (no brackets, exactly one space after colon):");
  console.error("  \x1b[32m<type>: <message>\x1b[0m  (e.g. \x1b[36mchore: message\x1b[0m)\n");
  console.error("Allowed standard commit types:");
  console.error("  \x1b[33m" + ALLOWED_TYPES.join(", ") + "\x1b[0m\n");
  console.error("Examples:");
  console.error("  \x1b[32m✓ feat: implement realtime SMS radar\x1b[0m");
  console.error("  \x1b[32m✓ fix: prevent splash progress bar reset\x1b[0m");
  console.error("  \x1b[32m✓ chore: update gitignore for binaries\x1b[0m");
  console.error("  \x1b[32m✓ docs: update design system specs\x1b[0m\n");
  process.exit(1);
}

process.exit(0);
